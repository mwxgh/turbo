import {
  BACKENDS,
  DATABASES,
  FRONTENDS,
  ORMS,
  type ScaffoldOptions,
} from '../options.js'
import { type FileTree, json, text } from '../tree.js'
import { V } from '../versions.js'
import { DATABASE_PROFILES, dockerCompose } from './database.js'

const labelOf = <T extends string>(list: { value: T; label: string }[], v: T) =>
  list.find((c) => c.value === v)!.label

/** Monorepo shell: pnpm workspace + Turborepo, shared types, local database, README. */
export function baseLayer(o: ScaffoldOptions): FileTree {
  const ormDocs: Record<ScaffoldOptions['orm'], string> = {
    prisma:
      'Schema: `apps/api/prisma/schema.prisma`. After a change: `pnpm db:migrate` (creates and applies a migration, regenerates the client).',
    drizzle:
      'Schema: `apps/api/src/db/schema.ts`. After a change: `pnpm db:generate` (writes a migration in `apps/api/drizzle/`), then `pnpm db:migrate`.',
    typeorm:
      'Entities: `apps/api/src/todos/todo.entity.ts`. In development the schema is synchronised on start (`DB_SYNCHRONIZE=true`); turn it off and add migrations before production.',
  }
  const stack = [
    `- Backend: **${labelOf(BACKENDS, o.backend)}** (\`apps/api\`, port 3001)`,
    `- ORM: **${labelOf(ORMS, o.orm)}**`,
    `- Database: **${labelOf(DATABASES, o.database)}** (\`docker-compose.yml\`)`,
    `- Frontend: **${labelOf(FRONTENDS, o.frontend)}** (\`apps/web\`, port 3000)`,
    '- Shared types: `packages/types` (used by api and web)',
  ].join('\n')

  return {
    'package.json': json({
      name: o.name,
      private: true,
      packageManager: `pnpm@${V.pnpm}`,
      engines: { node: `>=${V.node}` },
      scripts: {
        dev: 'turbo run dev',
        build: 'turbo run build',
        'check-types': 'turbo run check-types',
        'db:up': 'docker compose up -d --wait',
        'db:down': 'docker compose down',
        ...(o.orm === 'typeorm'
          ? {}
          : {
              'db:migrate': 'pnpm --filter api db:migrate',
              ...(o.orm === 'drizzle'
                ? { 'db:generate': 'pnpm --filter api db:generate' }
                : {}),
            }),
      },
      devDependencies: { turbo: V.turbo, typescript: V.typescript },
    }),
    'pnpm-workspace.yaml': text`
      packages:
        - 'apps/*'
        - 'packages/*'

      # Packages allowed to run install scripts
      allowBuilds:
        '@swc/core': true
        'esbuild': true
        'prisma': true
        '@prisma/engines': true
    `,
    'turbo.json': json({
      $schema: 'https://turborepo.dev/schema.json',
      tasks: {
        build: {
          dependsOn: ['^build'],
          outputs: ['dist/**', '.next/**', '!.next/cache/**'],
        },
        'check-types': { dependsOn: ['^build'] },
        dev: { dependsOn: ['^build'], cache: false, persistent: true },
      },
    }),
    '.gitignore': text`
      node_modules
      dist
      .next
      .turbo
      .env
      .env.local
      *.tsbuildinfo
      apps/api/src/generated
    `,
    '.node-version': `${V.node}\n`,
    '.editorconfig': text`
      root = true

      [*]
      charset = utf-8
      end_of_line = lf
      indent_size = 2
      indent_style = space
      insert_final_newline = true
      trim_trailing_whitespace = true
    `,
    'docker-compose.yml': dockerCompose(o),
    'README.md': [
      `# ${o.name}`,
      '',
      'Generated by Turbo Studio.',
      '',
      '## Stack',
      '',
      stack,
      '',
      '## Run it',
      '',
      '```bash',
      'pnpm install',
      'cp apps/api/.env.example apps/api/.env',
      'cp apps/web/.env.example apps/web/.env',
      `pnpm db:up            # ${DATABASE_PROFILES[o.database].label} on localhost:${DATABASE_PROFILES[o.database].port}`,
      o.orm === 'typeorm'
        ? '# the api creates the tables on start (DB_SYNCHRONIZE=true)'
        : o.orm === 'drizzle'
          ? 'pnpm db:generate && pnpm db:migrate'
          : 'pnpm db:migrate      # first migration',
      'pnpm dev              # web http://localhost:3000, api http://localhost:3001/api',
      '```',
      '',
      '## Database',
      '',
      ormDocs[o.orm],
      '',
      '## API',
      '',
      '| Method | Path | Body |',
      '| --- | --- | --- |',
      '| GET | `/api/health` | |',
      '| GET | `/api/todos` | |',
      '| POST | `/api/todos` | `{ "title": "…" }` |',
      '| PATCH | `/api/todos/:id` | `{ "title"?: "…", "done"?: true }` |',
      '| DELETE | `/api/todos/:id` | |',
      '',
    ].join('\n'),
    'packages/types/package.json': json({
      name: '@app/types',
      version: '0.0.0',
      private: true,
      type: 'module',
      exports: {
        '.': { types: './dist/index.d.ts', default: './dist/index.js' },
      },
      scripts: {
        build: 'tsc',
        dev: 'tsc --watch --preserveWatchOutput',
        'check-types': 'tsc --noEmit',
      },
      devDependencies: { typescript: V.typescript },
    }),
    'packages/types/tsconfig.json': json({
      compilerOptions: {
        target: 'ES2023',
        module: 'NodeNext',
        moduleResolution: 'NodeNext',
        declaration: true,
        strict: true,
        skipLibCheck: true,
        outDir: 'dist',
        rootDir: 'src',
      },
      include: ['src'],
    }),
    'packages/types/src/index.ts': text`
      /** A todo as the API returns it (JSON: dates are ISO strings). */
      export interface Todo {
        id: string
        title: string
        done: boolean
        createdAt: string
      }

      export interface CreateTodo {
        title: string
      }

      export interface UpdateTodo {
        title?: string
        done?: boolean
      }
    `,
  }
}
