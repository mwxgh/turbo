import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

import helper, { type DMMF } from '@prisma/generator-helper'

// CommonJS package: named runtime imports fail under ESM
const { generatorHandler } = helper

const HEADER = `/* Generated by \`pnpm db:types\` (packages/db/prisma/generators/types.ts). Do not edit. */\n`

// JSON shapes as the API sends them: DateTime → ISO string, Decimal/BigInt → string, Bytes → base64
const SCALARS: Record<string, string> = {
  String: 'string',
  Int: 'number',
  Float: 'number',
  Decimal: 'string',
  BigInt: 'string',
  Boolean: 'boolean',
  DateTime: 'string',
  Json: 'JsonValue',
  Bytes: 'string',
}

const doc = (text: string | undefined, indent = '') =>
  text ? `${indent}/** ${text.replaceAll('\n', `\n${indent} * `)} */\n` : ''

function renderEnum(e: DMMF.DatamodelEnum) {
  const values = e.values.map((v) => `  ${v.name}: '${v.name}',`).join('\n')
  return (
    `${doc(e.documentation)}export const ${e.name} = {\n${values}\n} as const\n\n` +
    `export type ${e.name} = (typeof ${e.name})[keyof typeof ${e.name}]\n`
  )
}

function renderEnums(enums: readonly DMMF.DatamodelEnum[]) {
  if (enums.length === 0) return `${HEADER}\nexport {}\n`
  return `${HEADER}\n${enums.map(renderEnum).join('\n')}`
}

// Relations are optional (present only when the API includes them) and depth-limited,
// so recursive models stay finite for TanStack DeepKeys.
function renderField(model: DMMF.Model, f: DMMF.Field) {
  if (f.kind === 'object') {
    const depth = f.type === model.name ? 1 : 2
    const type = `LimitDepth<${f.type}, ${depth}>`
    if (f.isList) return `  ${f.name}?: ${type}[]`
    return `  ${f.name}?: ${type}${f.isRequired ? '' : ' | null'}`
  }
  const base = f.kind === 'enum' ? f.type : (SCALARS[f.type] ?? 'unknown')
  const type = f.isList ? `${base}[]` : base
  return `  ${f.name}: ${type}${f.isRequired ? '' : ' | null'}`
}

function renderModels(models: readonly DMMF.Model[]) {
  const fields = models.flatMap((m) => m.fields)
  const enums = [
    ...new Set(fields.filter((f) => f.kind === 'enum').map((f) => f.type)),
  ]
  const helpers = [
    fields.some((f) => f.kind === 'object') && 'LimitDepth',
    fields.some((f) => f.type === 'Json') && 'JsonValue',
  ].filter(Boolean)
  const imports =
    (helpers.length
      ? `import type { ${helpers.join(', ')} } from '../helpers.js'\n`
      : '') +
    (enums.length
      ? `import type { ${enums.sort().join(', ')} } from './enums.js'\n`
      : '')
  const blocks = models.map(
    (m) =>
      `${doc(m.documentation)}export interface ${m.name} {\n${m.fields
        .filter((f) => f.kind !== 'unsupported')
        .map((f) => doc(f.documentation, '  ') + renderField(m, f))
        .join('\n')}\n}\n`,
  )
  return `${HEADER}\n${imports ? `${imports}\n` : ''}${blocks.join('\n')}`
}

generatorHandler({
  onManifest: () => ({ prettyName: '@repo/types' }),
  onGenerate: async ({ dmmf, generator }) => {
    const out = generator.output?.value
    if (!out) throw new Error('types generator: missing output')
    await mkdir(out, { recursive: true })
    await Promise.all([
      writeFile(path.join(out, 'enums.ts'), renderEnums(dmmf.datamodel.enums)),
      writeFile(
        path.join(out, 'models.ts'),
        renderModels(dmmf.datamodel.models),
      ),
    ])
  },
})
