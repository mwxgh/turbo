import { screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'

import { renderWithQuery } from '@/lib/test-utils'

import { toFolders } from './file-preview'
import { StudioConfigurator } from './studio-configurator'

const group = (name: string | RegExp) =>
  screen.getByRole('group', {
    name: typeof name === 'string' ? new RegExp(name) : name,
  })
const radio = (groupName: string | RegExp, name: string | RegExp) =>
  within(group(groupName)).getByRole('radio', { name })
const files = () => screen.getByRole('navigation', { name: 'Project files' })
const changeButton = (step: string) =>
  screen.getByRole('button', { name: new RegExp(`^Change ${step}`, 'i') })

describe('StudioConfigurator steps', () => {
  it('opens on the database step only, the preview shows the defaults', () => {
    renderWithQuery(<StudioConfigurator />)
    expect(group('1. Database')).toBeInTheDocument()
    expect(screen.queryByRole('group', { name: /Backend/ })).toBeNull()
    expect(
      screen.getByText(/Not picked yet, shown with defaults/),
    ).toHaveTextContent('Database, Backend, ORM, Frontend, Repository')
    expect(
      screen.getByRole('region', { name: 'File content' }),
    ).toHaveTextContent('Generated by Turbo Studio.')
  })

  it('records each pick, collapses the step and opens the next one', async () => {
    const user = userEvent.setup()
    renderWithQuery(<StudioConfigurator />)

    await user.click(radio('1. Database', /MongoDB/))
    expect(changeButton('database')).toHaveAccessibleName(/MongoDB/)

    // Backend: the ORMs of each backend for the chosen database are listed
    expect(radio('2. Backend', /Express/)).toHaveAccessibleDescription(
      /ORMs for MongoDB: Mongoose, No ORM/,
    )
    expect(radio('2. Backend', /Spring Boot/)).toBeDisabled()
    await user.click(radio('2. Backend', /Express/))

    // ORM: only the backend language's ORMs, the ones that do not fit the database disabled
    expect(radio('3. ORM', /Mongoose/)).toBeChecked()
    expect(radio('3. ORM', /Prisma/)).toBeDisabled()
    expect(
      within(group('3. ORM')).queryByRole('radio', { name: /Spring Data/ }),
    ).toBeNull()
    await user.click(radio('3. ORM', /No ORM/))

    await user.click(radio('4. Frontend', /React \(Vite\)/))

    // Repository last: a monorepo needs a tool before the step is done
    await user.click(radio('5. Repository', /Monorepo/))
    expect(group('Monorepo tool')).toBeInTheDocument()
    await user.click(radio('Monorepo tool', /Nx/))
    expect(changeButton('repository')).toHaveAccessibleName(/Monorepo · Nx/)

    expect(screen.queryByText(/Not picked yet/)).toBeNull()
    expect(screen.queryByRole('radio')).toBeNull()
    expect(
      within(files()).getByRole('button', { name: 'nx.json' }),
    ).toBeVisible()
    expect(
      within(files()).getByRole('button', { name: 'todos.router.ts' }),
    ).toBeVisible()
  })

  it('writes separate api/ and web/ folders when no monorepo is picked', async () => {
    const user = userEvent.setup()
    renderWithQuery(
      <StudioConfigurator />,
      undefined,
      '?database=postgres&backend=nest&orm=prisma&frontend=next',
    )
    await user.click(radio('5. Repository', /Separate folders/))
    expect(changeButton('repository')).toHaveAccessibleName(/Separate folders/)
    expect(within(files()).queryByText('apps')).toBeNull()
    expect(within(files()).getByText('api')).toBeInTheDocument()
  })

  it('reopens a step with Change, and asks for the ORM again when it no longer fits', async () => {
    const user = userEvent.setup()
    renderWithQuery(
      <StudioConfigurator />,
      undefined,
      '?repo=turbo&database=postgres&backend=nest&orm=prisma&frontend=next',
    )
    // A full link: every step recorded
    expect(screen.queryByRole('radio')).toBeNull()

    await user.click(changeButton('database'))
    await user.click(radio('1. Database', /Oracle/))

    // Prisma has no Oracle support: the ORM step opens again with TypeORM and a note
    expect(radio('3. ORM', /TypeORM/)).toBeChecked()
    expect(within(group('3. ORM')).getByRole('status')).toHaveTextContent(
      'Prisma does not fit NestJS with Oracle: switched to TypeORM.',
    )
  })

  it('moves with the arrow keys without closing the step; Enter records it', async () => {
    const user = userEvent.setup()
    renderWithQuery(<StudioConfigurator />)
    radio('1. Database', /PostgreSQL/).focus()
    await user.keyboard('{ArrowDown}')
    expect(radio('1. Database', /MySQL/)).toBeChecked()
    expect(group('1. Database')).toBeInTheDocument()

    await user.keyboard('{Enter}')
    expect(changeButton('database')).toHaveAccessibleName(/MySQL/)
    // Focus moved into the next step
    expect(radio('2. Backend', /NestJS/)).toHaveFocus()
  })

  it('ignores an ORM in the link that does not fit', () => {
    renderWithQuery(
      <StudioConfigurator />,
      undefined,
      '?database=mongodb&backend=nest&orm=prisma',
    )
    expect(changeButton('orm')).toHaveAccessibleName(/Mongoose/)
  })

  it('explains an invalid project name after leaving the field, and stops the preview', async () => {
    const user = userEvent.setup()
    renderWithQuery(<StudioConfigurator />)
    const input = screen.getByLabelText('Project name')
    await user.clear(input)
    await user.type(input, 'My App')
    await user.tab()
    expect(input).toHaveAttribute('aria-invalid', 'true')
    expect(screen.getByRole('alert')).toHaveTextContent(/lowercase letters/)
    expect(screen.getByText('Nothing to preview yet')).toBeInTheDocument()
  })

  it('opens a file from the tree', async () => {
    const user = userEvent.setup()
    renderWithQuery(<StudioConfigurator />)
    await user.click(screen.getByRole('button', { name: 'docker-compose.yml' }))
    expect(
      screen.getByRole('region', { name: 'File content' }),
    ).toHaveTextContent('postgres:18-alpine')
  })
})

describe('toFolders', () => {
  it('nests paths into folders and files', () => {
    const root = toFolders([
      'apps/api/main.ts',
      'apps/web/page.tsx',
      'README.md',
    ])
    expect(root.files.map((f) => f.name)).toEqual(['README.md'])
    expect(root.folders[0]!.folders.map((f) => f.name)).toEqual(['api', 'web'])
  })
})
