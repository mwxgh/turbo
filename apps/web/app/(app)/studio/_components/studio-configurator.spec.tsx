import { screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { apiFetch } from '@/lib/api'
import { type StudioCatalog, studioKeys } from '@/lib/queries/studio'
import { createTestQueryClient, renderWithQuery } from '@/lib/test-utils'

import { toFolders } from './file-preview'
import { StudioConfigurator } from './studio-configurator'

vi.mock('@/lib/api', () => ({
  ApiError: class extends Error {},
  apiFetch: Object.assign(vi.fn(), { raw: vi.fn() }),
}))

const choice = <T extends string>(
  value: T,
  label: string,
  planned?: boolean,
) => ({ value, label, description: `${label} description`, planned })

/** GET /api/studio/options as the api serves it (the parts these tests use). */
const CATALOG: StudioCatalog = {
  namePattern: '^[a-z][a-z0-9-]{1,49}$',
  defaults: {
    name: 'my-app',
    repo: 'turbo',
    backend: 'nest',
    database: 'postgres',
    orm: 'prisma',
    frontend: 'next',
  },
  repos: [
    choice('turbo', 'Turborepo'),
    choice('nx', 'Nx'),
    choice('single', 'No monorepo'),
  ],
  databases: [
    choice('postgres', 'PostgreSQL'),
    choice('mysql', 'MySQL'),
    choice('oracle', 'Oracle'),
    choice('mongodb', 'MongoDB'),
  ],
  backends: [
    {
      ...choice('nest', 'NestJS'),
      language: 'typescript',
      monorepoUnavailable: null,
    },
    {
      ...choice('express', 'Express'),
      language: 'typescript',
      monorepoUnavailable: null,
    },
    {
      ...choice('spring', 'Spring Boot', true),
      language: 'java',
      monorepoUnavailable: 'Needs a TypeScript backend',
    },
  ],
  orms: [
    choice('prisma', 'Prisma'),
    choice('drizzle', 'Drizzle'),
    choice('typeorm', 'TypeORM'),
    choice('mongoose', 'Mongoose'),
    choice('jpa', 'Spring Data JPA', true),
    choice('none', 'No ORM'),
  ],
  frontends: [
    choice('next', 'Next.js'),
    choice('react', 'React (Vite)'),
    choice('nuxt', 'Nuxt'),
  ],
  ormsByStack: {
    typescript: {
      postgres: ['prisma', 'drizzle', 'typeorm'],
      mysql: ['prisma', 'drizzle', 'typeorm'],
      oracle: ['typeorm'],
      mongodb: ['mongoose', 'none'],
    },
    java: { postgres: ['jpa'], mysql: ['jpa'], oracle: ['jpa'], mongodb: [] },
    go: { postgres: [], mysql: [], oracle: [], mongodb: [] },
    python: { postgres: [], mysql: [], oracle: [], mongodb: [] },
  },
}

const FILES = {
  'README.md': '# my-app\n\nGenerated by Turbo Studio.\n',
  'docker-compose.yml': 'services:\n  db:\n    image: postgres:18-alpine\n',
  'apps/api/package.json': '{}\n',
}

function render(search = '') {
  const client = createTestQueryClient()
  client.setQueryData(studioKeys.options, CATALOG)
  return renderWithQuery(<StudioConfigurator />, client, search)
}

const FULL =
  '?repo=turbo&database=postgres&backend=nest&orm=prisma&frontend=next'

const group = (name: string | RegExp) =>
  screen.getByRole('group', {
    name: typeof name === 'string' ? new RegExp(name) : name,
  })
const radio = (groupName: string | RegExp, name: string | RegExp) =>
  within(group(groupName)).getByRole('radio', { name })
const changeButton = (step: string) =>
  screen.getByRole('button', { name: new RegExp(`^Change ${step}`, 'i') })
const generateButton = () =>
  screen.getByRole('button', { name: /Generate project/ })

beforeEach(() => {
  vi.mocked(apiFetch).mockReset()
  vi.mocked(apiFetch.raw).mockReset()
})

describe('StudioConfigurator steps', () => {
  it('opens on the database step only, nothing to generate yet', () => {
    render()
    expect(group('1. Database')).toBeInTheDocument()
    expect(screen.queryByRole('group', { name: /Backend/ })).toBeNull()
    expect(screen.queryByRole('button', { name: /Generate/ })).toBeNull()
    expect(screen.getByRole('list', { name: 'Steps' })).toHaveTextContent(
      /Database.*Generate/,
    )
  })

  it('records each pick, collapses the step and opens the next; the last one offers Generate', async () => {
    const user = userEvent.setup()
    render()

    await user.click(radio('1. Database', /MongoDB/))
    expect(changeButton('database')).toHaveAccessibleName(/MongoDB/)

    // Backend: the ORMs of each backend for the chosen database are listed
    expect(radio('2. Backend', /Express/)).toHaveAccessibleDescription(
      /ORMs for MongoDB: Mongoose, No ORM/,
    )
    expect(radio('2. Backend', /Spring Boot/)).toBeDisabled()
    await user.click(radio('2. Backend', /Express/))

    // ORM: only the backend language's ORMs, the ones that do not fit the database disabled
    expect(radio('3. ORM', /Mongoose/)).toBeChecked()
    expect(radio('3. ORM', /Prisma/)).toBeDisabled()
    expect(
      within(group('3. ORM')).queryByRole('radio', { name: /Spring Data/ }),
    ).toBeNull()
    await user.click(radio('3. ORM', /No ORM/))

    await user.click(radio('4. Frontend', /React \(Vite\)/))
    expect(screen.queryByRole('button', { name: /Generate/ })).toBeNull()

    // Repository last: a monorepo needs a tool before the step is done
    await user.click(radio('5. Repository', /Monorepo/))
    expect(group('Monorepo tool')).toBeInTheDocument()
    await user.click(radio('Monorepo tool', /Nx/))
    expect(changeButton('repository')).toHaveAccessibleName(/Monorepo · Nx/)

    expect(screen.queryByRole('radio')).toBeNull()
    const review = screen.getByRole('region', { name: 'Ready to generate' })
    expect(review).toHaveTextContent(
      /MongoDB.*Express.*No ORM.*React \(Vite\).*Monorepo · Nx/,
    )
    expect(generateButton()).toBeEnabled()
  })

  it('reopens a step with Change, and asks for the ORM again when it no longer fits', async () => {
    const user = userEvent.setup()
    render(FULL)
    // A full link: every step recorded
    expect(screen.queryByRole('radio')).toBeNull()

    await user.click(changeButton('database'))
    await user.click(radio('1. Database', /Oracle/))

    // Prisma has no Oracle support: the ORM step opens again with TypeORM and a note
    expect(radio('3. ORM', /TypeORM/)).toBeChecked()
    expect(within(group('3. ORM')).getByRole('status')).toHaveTextContent(
      'Prisma does not fit NestJS with Oracle: switched to TypeORM.',
    )
    expect(screen.queryByRole('button', { name: /Generate/ })).toBeNull()
  })

  it('moves with the arrow keys without closing the step; Enter records it', async () => {
    const user = userEvent.setup()
    render()
    radio('1. Database', /PostgreSQL/).focus()
    await user.keyboard('{ArrowDown}')
    expect(radio('1. Database', /MySQL/)).toBeChecked()
    expect(group('1. Database')).toBeInTheDocument()

    await user.keyboard('{Enter}')
    expect(changeButton('database')).toHaveAccessibleName(/MySQL/)
    // Focus moved into the next step
    expect(radio('2. Backend', /NestJS/)).toHaveFocus()
  })

  it('ignores an ORM in the link that does not fit', () => {
    render('?database=mongodb&backend=nest&orm=prisma')
    expect(changeButton('orm')).toHaveAccessibleName(/Mongoose/)
  })

  it('explains an invalid project name after leaving the field and blocks Generate', async () => {
    const user = userEvent.setup()
    render(FULL)
    const input = screen.getByLabelText('Project name')
    await user.clear(input)
    await user.type(input, 'My App')
    await user.tab()
    expect(input).toHaveAttribute('aria-invalid', 'true')
    expect(screen.getByRole('alert')).toHaveTextContent(/lowercase letters/)
    expect(generateButton()).toBeDisabled()
  })
})

describe('StudioConfigurator generate', () => {
  afterEach(() => vi.restoreAllMocks())

  it('generates on the server, shows the files, and goes back to the options', async () => {
    const user = userEvent.setup()
    vi.mocked(apiFetch).mockResolvedValue({ files: FILES })
    render(FULL)

    await user.click(generateButton())
    expect(apiFetch).toHaveBeenCalledWith('/studio/preview', {
      method: 'POST',
      body: expect.stringContaining('"orm":"prisma"') as string,
    })
    expect(
      screen.getByRole('heading', { name: /my-app is ready/ }),
    ).toHaveFocus()
    expect(screen.getByText(/3 files/)).toBeInTheDocument()
    expect(
      screen.getByRole('region', { name: 'File content' }),
    ).toHaveTextContent('Generated by Turbo Studio.')
    await user.click(screen.getByRole('button', { name: 'docker-compose.yml' }))
    expect(
      screen.getByRole('region', { name: 'File content' }),
    ).toHaveTextContent('postgres:18-alpine')

    // Back to the form: same options, no second request
    await user.click(screen.getByRole('button', { name: /Change options/ }))
    await user.click(
      screen.getByRole('button', { name: /View generated files/ }),
    )
    expect(apiFetch).toHaveBeenCalledTimes(1)
  })

  it('downloads the zip of the same options', async () => {
    const user = userEvent.setup()
    vi.mocked(apiFetch).mockResolvedValue({ files: FILES })
    const raw = vi
      .mocked(apiFetch.raw)
      .mockResolvedValue(new Response(new Blob(['PK'])))
    URL.createObjectURL = vi.fn(() => 'blob:zip')
    const revoke = vi.fn()
    URL.revokeObjectURL = revoke
    const click = vi
      .spyOn(HTMLAnchorElement.prototype, 'click')
      .mockImplementation(() => {})

    render(FULL)
    await user.click(generateButton())
    await user.click(
      screen.getByRole('button', { name: /Download my-app\.zip/ }),
    )

    expect(raw).toHaveBeenCalledWith('/studio/generate', {
      method: 'POST',
      body: expect.stringContaining('"name":"my-app"') as string,
    })
    expect(click).toHaveBeenCalled()
    expect(revoke).toHaveBeenCalledWith('blob:zip')
  })
})

describe('toFolders', () => {
  it('nests paths into folders and files', () => {
    const root = toFolders([
      'apps/api/main.ts',
      'apps/web/page.tsx',
      'README.md',
    ])
    expect(root.files.map((f) => f.name)).toEqual(['README.md'])
    expect(root.folders[0]!.folders.map((f) => f.name)).toEqual(['api', 'web'])
  })
})
